create table pedidos (
    id bigint generated by default as identity primary key,
    usuario_id uuid,
    direccion_entrega varchar(180) not null,
    telefono_contacto varchar(15) not null,
    referencia_entrega varchar(250),
    subtotal numeric(10, 2) not null check (subtotal >= 0),
    descuento_total numeric(10, 2) not null default 0 check (descuento_total >= 0),
    total numeric(10, 2) not null check (total >= 0),
    estado varchar(20) not null default 'EN_ESPERA' check (estado in ('EN_ESPERA', 'ENTREGADO')),
    creado_en timestamp with time zone not null
);

create index pedidos_usuario_id_idx on pedidos (usuario_id, creado_en desc);

create table pedido_detalles (
    id bigint generated by default as identity primary key,
    pedido_id bigint not null references pedidos (id) on delete cascade,
    producto_id bigint not null references productos (id) on delete restrict,
    cantidad integer not null check (cantidad > 0),
    precio_unitario numeric(10, 2) not null check (precio_unitario > 0)
);

create index pedido_detalles_pedido_id_idx on pedido_detalles (pedido_id);
