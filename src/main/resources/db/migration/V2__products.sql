create table productos (
    id bigint generated by default as identity primary key,
    nombre varchar(100) not null,
    categoria varchar(20) not null,
    descripcion varchar(500) not null,
    precio numeric(8, 2) not null check (precio > 0),
    stock integer not null check (stock between 0 and 999999),
    precio_promocional numeric(8, 2) check (precio_promocional > 0 and precio_promocional < precio),
    version bigint not null default 0,
    constraint productos_categoria_valida check (
        categoria in ('FRUTAS_Y_VERDURAS', 'DESPENSA', 'LACTEOS_Y_HUEVOS', 'BEBIDAS', 'LIMPIEZA', 'OTROS')
    )
);

create index productos_categoria_id_idx on productos (categoria, id desc);
